from re import finditer

def expression_to_tokens(expr):
    '''Токенизация полученного выражения с терминала: убираем с выражения пробелы;
    с помощью регулярного выражения проводим токенизацию: 
        - Первая часть (до первого знака "|") ищет число со знаком, только если перед
        ним стоит начало строки ^, оператор или открывающаяся скобка.
        - Вторая часть (между двумя знаками "|") ищет число со знаком только если перед ним нет
        другой цифры.
        - Третья часть (после последнего знака "|"): если совпадения с числами не произошло, символ обрабатывается 
        как самостоятельный оператор.'''
    expression = expr.replace(" ", "")
    reg_exp = r"(?<=^[+\-*/(])[-+]?\d*(?:\.+\d*)?|(?<!\d)[-+]?\d*(?:\.+\d*)?|[+\-*/()]"
    pre_tokens = [x.group() for x in finditer(reg_exp, expression)]
    tokens = [token for token in pre_tokens if token != ""]
    return tokens

